"""The evaluation report (docs/eval/report.md): metrics and failure categories only.

The report holds counts, rates, costs, durations, statuses, model ids and failure category names. It never
holds a value read from a sample (labels, coordinates, depths, project names, error texts, page numbers)
and names files only by the short ids given on the command line.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable
from pathlib import Path

from app.eval.compare import METRICS, Tally
from app.eval.runner import EvalRun, FileRun

METRIC_TITLES = {
    "borehole_count": "Borehole count (files)",
    "labels": "Labels found (boreholes)",
    "coordinates": "Coordinates as printed",
    "crs_status": "CRS status",
    "total_depth": "Total depth",
    "layer_count": "Layer count",
    "unplotted_reason": "Unplotted reason",
    "duplicates": "Duplicates detected (files)",
}
_COLUMNS = {
    "labels": "Labels",
    "coordinates": "Coord.",
    "crs_status": "CRS",
    "total_depth": "Depth",
    "layer_count": "Layers",
    "unplotted_reason": "Unplotted",
    "duplicates": "Dupl.",
}
STOP_TEXT = {"cost_cap": "eval cost cap (--max-usd)", "provider_budget": "PROVIDER_BUDGET_USD"}


def _duration(seconds: float) -> str:
    if seconds < 60:
        return f"{seconds:.1f} s"
    minutes, rest = divmod(round(seconds), 60)
    if minutes < 60:
        return f"{minutes} min {rest:02d} s"
    hours, minutes = divmod(minutes, 60)
    return f"{hours} h {minutes:02d} min"


def _rate(match: int, compared: int) -> str:
    return f"{100 * match / compared:.0f} %" if compared else "–"


def _cell(tally: Tally) -> str:
    if tally.compared:
        return f"{tally.match}/{tally.compared}"
    return "n/c" if tally.not_comparable else "–"


def _row(cells: Iterable[object]) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _status(current: FileRun) -> str:
    if current.not_started:
        return f"not started ({current.not_started})"
    statuses = Counter(d.status for d in current.documents)
    return ", ".join(f"{s} ×{n}" if n > 1 else s for s, n in sorted(statuses.items())) or "–"


def render(run: EvalRun) -> str:
    started = [f for f in run.files if f.started]
    documents = [d for f in started for d in f.documents]
    totals = {m: Tally() for m in METRICS}
    failures: Counter[str] = Counter()
    failure_files: dict[str, list[str]] = {}
    not_comparable: Counter[str] = Counter()
    matched = unexpected = 0
    for current in run.files:
        for category, count in current.failures.items():
            failures[category] += count
            failure_files.setdefault(category, []).append(current.short_id)
        if current.comparison is None:
            continue
        for metric in METRICS:
            totals[metric].add(current.comparison.tallies[metric])
        not_comparable.update(current.comparison.not_comparable)
        matched += current.comparison.matched
        unexpected += current.comparison.unexpected

    lines = [
        "# Evaluation report",
        "",
        f"Generated by `python -m app.eval` on {run.started_at:%Y-%m-%d %H:%M} UTC. Metrics and failure "
        "categories only: no labels, coordinates, depths or other values from the sample files. Files "
        "appear only as the ids given on the command line.",
        "",
        "## Run",
        "",
        "| Item | Value |",
        "|---|---|",
        _row(("Files planned", len(run.files))),
        _row(("Files run", len(started))),
        _row(("Files not started", len(run.files) - len(started))),
        _row(("Stopped by", STOP_TEXT.get(run.stopped_by or "", "–"))),
        _row(("Cost cap", f"{run.max_usd:.2f} USD")),
        _row(("Spent in this run", f"{run.spent_usd:.4f} USD")),
        _row(
            (
                "PROVIDER_BUDGET_USD",
                "not set" if run.provider_budget_usd is None else f"{run.provider_budget_usd:.2f} USD",
            )
        ),
        _row(("Duration", _duration(run.duration_s))),
        _row(
            (
                "Documents",
                f"{len(documents)} ({sum(d.finished_before for d in documents)} finished in an earlier run, "
                "reused at no cost)",
            )
        ),
        _row(
            (
                "Pages",
                f"{sum(d.pages for d in documents)} ({sum(d.pages_ocr for d in documents)} read by OCR)",
            )
        ),
        _row(("Provider calls", ", ".join(f"{p} {n}" for p, n in sorted(run.calls.items())) or "none")),
        _row(
            (
                "Models (as returned)",
                "; ".join(f"{p}: {', '.join(m)}" for p, m in run.models.items()) or "none",
            )
        ),
        "",
        "## Accuracy",
        "",
        "Per-borehole metrics count boreholes whose label was found; a borehole that was not found counts "
        "once, under labels. With a page excerpt only the boreholes whose pages all lie inside it are "
        "compared.",
        "",
        "| Metric | Compared | Match | Rate | Not comparable |",
        "|---|---|---|---|---|",
    ]
    for metric in METRICS:
        tally = totals[metric]
        lines.append(
            _row(
                (
                    METRIC_TITLES[metric],
                    tally.compared,
                    tally.match,
                    _rate(tally.match, tally.compared),
                    tally.not_comparable,
                )
            )
        )
    lines += [
        "",
        f"Label precision: {_rate(matched, matched + unexpected)} ({unexpected} stored label(s) match no "
        "expected borehole).",
        "",
        "## Files",
        "",
        _row(
            (
                "File",
                "Status",
                "Excerpt pages",
                "Pages",
                "OCR pages",
                "Duration",
                "Cost USD",
                "Expected",
                "Found",
                *(_COLUMNS[m] for m in METRICS if m != "borehole_count"),
            )
        ),
        "|" + "---|" * (9 + len(METRICS) - 1),
    ]
    for current in run.files:
        comparison = current.comparison
        expected = "–"
        found = "–"
        cells = ["–"] * (len(METRICS) - 1)
        if comparison is not None:
            if comparison.expected_in_scope is not None:
                expected = str(comparison.expected_in_scope)
            elif comparison.tallies["borehole_count"].not_comparable:
                expected = "n/c"
            found = str(comparison.found)
            cells = [_cell(comparison.tallies[m]) for m in METRICS if m != "borehole_count"]
        docs = current.documents
        lines.append(
            _row(
                (
                    current.short_id,
                    _status(current),
                    current.planned.excerpt_pages or "–",
                    sum(d.pages for d in docs) if current.started else "–",
                    sum(d.pages_ocr for d in docs) if current.started else "–",
                    _duration(current.duration_s) if current.started else "–",
                    f"{current.cost_usd:.4f}" if current.started else "–",
                    expected,
                    found,
                    *cells,
                )
            )
        )
    lines += ["", "## Failure categories", ""]
    if failures:
        lines += ["| Category | Count | Files |", "|---|---|---|"]
        for category, count in sorted(failures.items(), key=lambda item: (-item[1], item[0])):
            lines.append(_row((category, count, ", ".join(dict.fromkeys(failure_files[category])))))
    else:
        lines.append("None.")
    lines += ["", "## Not comparable", ""]
    if not_comparable:
        lines += ["| Metric: reason | Count |", "|---|---|"]
        for reason, count in sorted(not_comparable.items()):
            lines.append(_row((reason, count)))
    else:
        lines.append("None.")
    lines += [
        "",
        "## Cost and calls per file",
        "",
        "| File | Estimate USD | Cost USD | Calls |",
        "|---|---|---|---|",
    ]
    for current in run.files:
        lines.append(
            _row(
                (
                    current.short_id,
                    f"{current.estimate_usd:.4f}",
                    f"{current.cost_usd:.4f}" if current.started else "–",
                    ", ".join(f"{p} {n}" for p, n in sorted(current.calls.items())) or "–",
                )
            )
        )
    return "\n".join(lines) + "\n"


def write_report(run: EvalRun, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(run), encoding="utf-8")
    return path
