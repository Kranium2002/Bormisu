"""Alembic: upgrade head on an empty database creates exactly the models' schema (no drift)."""

from __future__ import annotations

import asyncpg
import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

from app.config import BACKEND_DIR
from tests.conftest import TEST_DATABASE_URL, _plain_dsn

pytestmark = pytest.mark.db


async def test_upgrade_head_matches_models(database: None) -> None:
    name = (make_url(TEST_DATABASE_URL).database or "geomemory_test") + "_migrations"
    admin = await asyncpg.connect(_plain_dsn(TEST_DATABASE_URL, "postgres"))
    try:
        await admin.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
        await admin.execute(f'CREATE DATABASE "{name}"')
    finally:
        await admin.close()
    url = make_url(TEST_DATABASE_URL).set(database=name).render_as_string(hide_password=False)
    engine = create_async_engine(url)
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "migrations"))

    def upgrade(connection: object) -> None:
        config.attributes["connection"] = connection
        command.upgrade(config, "head")

    def check(connection: object) -> None:
        config.attributes["connection"] = connection
        command.check(config)  # raises AutogenerateDiffsDetected on drift

    try:
        async with engine.begin() as conn:
            await conn.run_sync(upgrade)
        async with engine.connect() as conn:
            await conn.run_sync(check)
            procrastinate = await conn.exec_driver_sql("SELECT to_regclass('procrastinate_jobs')")
            assert procrastinate.scalar() is not None
    finally:
        await engine.dispose()
