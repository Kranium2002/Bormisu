/** The generated sheet's view model (fictional borehole): labels per language, values from the record only. */
import { describe, expect, it } from 'vitest';
import { K } from '../../domain/keys';
import { makeBorehole, makeLayer, makeValue } from '../../test/fixtures';
import { descriptionLanguage, sheetLang, sheetModel, sheetT } from './sheetModel';

const TODAY = new Date('2026-10-17T12:00:00Z');

function borehole() {
  const b = makeBorehole({
    sourceFile: 'fictional_report.pdf',
    finalDepth: 6,
    layers: [
      makeLayer({ n: 1, from: 0, to: 2.5, lithology: 'Silt, sandy', lithologyAsPrinted: 'Schluff, sandig', din: 'U', dinNotation: 'U, s', consistency: 'stiff' }),
      makeLayer({ n: 2, from: 2.5, to: 6, lithology: 'Sand', lithologyAsPrinted: '', din: 'S' }),
    ],
  });
  b.values = b.values.filter((v) => v.key !== K.lithology(1) && v.key !== K.lithology(2));
  b.values.push(
    makeValue({ key: K.client, value: 'Fictional Client', status: 'approved' }),
    makeValue({ key: K.lithology(1), group: 'layer', layer: 1, value: 'Silt, sandy', raw: 'Schluff, sandig' }),
  );
  return b;
}

describe('sheetLang / sheetT', () => {
  it('is English unless ?lang=de', () => {
    expect(sheetLang(null)).toBe('en');
    expect(sheetLang('fr')).toBe('en');
    expect(sheetLang('de')).toBe('de');
  });

  it('translates labels for the German sheet only', () => {
    expect(sheetT('en', 'Final depth')).toBe('Final depth');
    expect(sheetT('de', 'Final depth')).toBe('Endteufe');
    expect(sheetT('de', 'some text without a German entry')).toBe('some text without a German entry');
  });
});

describe('sheetModel', () => {
  it('fills the header from the record and says "not in source" for what it does not state', () => {
    const m = sheetModel(borehole(), 'en', { today: TODAY });
    const field = (label: string) => m.header.find((f) => f.label === label)?.cell;
    expect(field('Client')).toEqual({ text: 'Fictional Client', missing: false, unreviewed: false });
    expect(field('Contractor')).toEqual({ text: 'not in source', missing: true, unreviewed: false });
    expect(field('Final depth')).toMatchObject({ text: '6.00 m', unreviewed: true });
    expect(m.footer).toBe('Generated by Bormisu from fictional_report.pdf on 2026-10-17');
  });

  it('shows English descriptions in EN and the as-printed words in DE, saying "as printed" for a log that is not German', () => {
    const b = borehole();
    expect(sheetModel(b, 'en', { today: TODAY }).layers[0].description.text).toBe('Silt, sandy');
    const de = sheetModel(b, 'de', { today: TODAY, pages: [{ n: 1, language: 'en' }] });
    expect(de.layers[0].description.text).toBe('Schluff, sandig');
    expect(de.descriptionHead).toBe('Beschreibung (wie gedruckt)');
    // Nothing printed for layer 2: the English text, marked as such, never an invented German one.
    expect(de.layers[1].description.text).toBe('Sand (englisch)');
    expect(sheetModel(b, 'de', { today: TODAY, pages: [{ n: 1, language: 'de' }] }).descriptionHead).toBe('Beschreibung');
  });

  it('labels and review state follow the sheet language', () => {
    const de = sheetModel(borehole(), 'de', { today: TODAY });
    expect(de.header.map((f) => f.label)).toContain('Endteufe');
    expect(de.review.text).toMatch(/^\d+ von \d+ Werten geprüft$/);
    expect(de.footer).toBe('Erstellt von Bormisu aus fictional_report.pdf am 2026-10-17');
  });

  it('lists layers with DIN notation and consistency, and shows TCR / RQD only when a layer has them', () => {
    const m = sheetModel(borehole(), 'en', { today: TODAY });
    expect(m.layers[0]).toMatchObject({ range: '0.00–2.50', din: 'U, s', consistency: 'stiff' });
    expect(m.hasCore).toBe(false);
  });

  it('reads the description language from the record before the page', () => {
    const b = borehole();
    expect(descriptionLanguage(b, [{ n: 1, language: 'en' }])).toBe('en');
    b.values.push(makeValue({ key: 'stratigraphy[0].description_language', field: 'description_language', value: 'de' }));
    expect(descriptionLanguage(b, [{ n: 1, language: 'en' }])).toBe('de');
  });
});
